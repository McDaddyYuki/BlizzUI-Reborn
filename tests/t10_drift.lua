-- Blizzard code that re-anchors frames must not undo the layout
dofile(TESTS_DIR .. "lib.lua")
H.login()
local function at(id)
    local l, b = T.rect(id)
    local e = A.draft.frames[id]
    local el, eb = T.expectedRect(id, e.point, e.x, e.y)
    return near(l, el, 1) and near(b, eb, 1)
end
UIParent_ManageFramePositions(); H.tick(0.05, 2)
check(at("cast") and at("stance") and at("totems"), "frame manager does not move managed frames back")
MOCK.repWatched = true; MainMenuExpBar:Hide(); ReputationWatchBar_Update(); H.tick(0.05, 2)
local p, rel = ReputationWatchBar:GetPoint(1)
check(rel == A.elements.statusbars.frame, "rep bar stays in the status bar holder at max level")
MainMenuExpBar:Show(); ReputationWatchBar_Update(); H.tick(0.05, 2)
p, rel = ReputationWatchBar:GetPoint(1)
check(rel == MainMenuExpBar, "rep bar stacks above xp bar")
check(near(ReputationWatchBar:GetScale(), .5), "rep bar keeps its layout size after Blizzard update")
MoveMicroButtons("BOTTOMLEFT", VehicleMenuBar, "BOTTOMLEFT", 10, 10); H.tick(0.3, 3)
local mp, mrel = CharacterMicroButton:GetPoint(1)
check(mrel == VehicleMenuBar, "vehicle keeps its micro buttons")
MoveMicroButtons("BOTTOMLEFT", MainMenuBarArtFrame, "BOTTOMLEFT", 552, 2); H.tick(0.3, 3)
check(at("micro"), "micro menu returns to its layout spot after the vehicle")
PetActionBarFrame.slideTimer = 0; PetActionBar_OnUpdate(PetActionBarFrame); H.tick(0.3, 3)
check(at("petbar"), "pet bar slide does not break layout")
FCF_RestorePositionAndDimensions(ChatFrame1); H.tick(0.05, 2)
check(at("chat"), "chat frame restore is undone")
ShowBonusActionBar(); H.tick(0.05, 2)
check(near(BonusActionButton1:GetLeft(), ActionButton1:GetLeft()), "bonus bar follows bar 1")
