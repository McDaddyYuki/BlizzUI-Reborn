dofile(TESTS_DIR .. "lib.lua")
ActionBarUpButton:EnableMouse(true); ActionBarDownButton:EnableMouse(true)
H.login()
-- Modern hides the page arrows
check(ActionBarUpButton:GetAlpha() == 0 and not ActionBarUpButton:IsMouseEnabled(), "Modern hides the up arrow")
check(ActionBarDownButton:GetAlpha() == 0 and MainMenuBarPageNumber:GetAlpha() == 0, "Modern hides down arrow and page number")
T.open()
local c = A.editor.checks.paging
check(c and c:IsShown() and not c:GetChecked(), "Page Arrows listed in Edit Mode, unchecked")
H.click(c)
check(ActionBarUpButton:GetAlpha() == 1 and ActionBarUpButton:IsMouseEnabled(), "checking it shows the arrows")
check(T.overlay("paging"):IsShown(), "arrows get a selection box when shown")
A.db.editor.snap = false
local l0, b0 = T.rect("paging")
T.dragElement("paging", -120, 60)
local l1, b1 = T.rect("paging")
check(near(l1 - l0, -120, 1) and near(b1 - b0, 60, 1), "arrows can be dragged")
A:SelectElement("paging")
A.settingsDialog.pages.paging.controls[1].ctl:Commit(80)
check(near(ActionBarUpButton:GetEffectiveScale() / UIParent:GetEffectiveScale(), .8, .01), "arrows can be resized")
H.click(c)
check(ActionBarUpButton:GetAlpha() == 0 and not T.overlay("paging"):IsShown(), "unchecking hides them again")
H.click(A.editor.revert)
-- Classic: native arrows
A:LoadPreset("Classic")
local p, rel = ActionBarUpButton:GetPoint(1)
check(rel == MainMenuBarArtFrame and ActionBarUpButton:GetAlpha() == 1 and ActionBarUpButton:IsMouseEnabled(), "Classic restores native arrows")
-- strata: moved bars sit below normal windows
A:LoadPreset("Modern")
check(ActionButton1:GetFrameStrata() == "LOW" and MultiBarRightButton1:GetFrameStrata() == "LOW", "moved action bars use LOW strata")
check(PetActionButton1:GetFrameStrata() == "LOW" and ShapeshiftButton1:GetFrameStrata() == "LOW", "pet/stance bars use LOW strata")
local questLog = CreateFrame("Frame", "NxQuestD", UIParent); questLog:SetFrameStrata("MEDIUM")
local order = { BACKGROUND = 1, LOW = 2, MEDIUM = 3, HIGH = 4, DIALOG = 5 }
check(order[ActionButton1:GetFrameStrata()] < order[questLog:GetFrameStrata()], "a MEDIUM window (Carbonite quest log) draws above the bars")
A:LoadPreset("Classic")
check(ActionButton1:GetFrameStrata() == "MEDIUM", "Classic restores native strata")
-- Modern layouts round-trip through share strings (entries without a position)
A:LoadPreset("Modern")
local data, name = A:Decode(A:Export())
check(data and data.frames.paging and data.frames.paging.enabled == false, "Modern exports/imports with hidden arrows")
