dofile(TESTS_DIR .. "lib.lua")
H.login()
T.open()
H.click(A.editor.keybind)
check(A.keybinding and A.quickKeybind:IsShown(), "Quick Keybind mode starts from Edit Mode")
check(not A.editor:IsShown() and not T.overlay("action1"):IsShown(), "edit overlays hidden so buttons can be hovered")
local keys = BlizzUIRebornQuickKeybindKeys
H.hover(ActionButton1); H.tick(0.11)
H.key(keys, "Q")
check(GetBindingAction("Q") == "ACTIONBUTTON1", "Q bound to Action Button 1")
check(MOCK.savedBindings, "bindings saved")
MOCK.shift = true; H.hover(MultiBarLeftButton3); H.key(keys, "E"); MOCK.shift = false
check(GetBindingAction("SHIFT-E") == "MULTIACTIONBAR4BUTTON3", "modifier binding on bar 5")
H.hover(PetActionButton2); H.key(keys, "F")
check(GetBindingAction("F") == "BONUSACTIONBUTTON2", "pet bar binding")
H.hover(ActionButton1); H.key(keys, "Q")
check(GetBindingAction("Q") == "", "pressing the same key again unbinds")
H.hover(UIParent); H.key(keys, "Z")
check(GetBindingAction("Z") == "", "no binding when not hovering a button")
H.key(keys, "LSHIFT")
H.key(keys, "ESCAPE")
check(not A.keybinding and not A.quickKeybind:IsShown(), "Escape leaves Quick Keybind")
check(A.editor:IsShown() and T.overlay("action1"):IsShown(), "back in Edit Mode afterwards")
-- combat stops it
A:StartQuickKeybind()
H.enterCombat()
check(not A.keybinding, "combat ends Quick Keybind")
H.leaveCombat()
