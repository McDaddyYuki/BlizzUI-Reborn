-- Behaviour verified against the real 3.3.5 FrameXML during the audit
dofile(TESTS_DIR .. "lib.lua")
SHOW_MULTI_ACTIONBAR_1 = 1; MultiActionBar_Update()
H.login()
T.open()
A.db.editor.snap = false
-- buffs: Blizzard re-anchors BuffFrame/TempEnchant to ConsolidatedBuffs on every aura update
BuffFrame_UpdateAllBuffAnchors()
check(#MOCK.errors == 0, "Blizzard buff re-anchoring causes no anchor loop")
T.dragElement("buffs", -60, -30)
BuffFrame_UpdateAllBuffAnchors(); H.tick(0.1, 2)
local e = A.draft.frames.buffs
local l, b = T.rect("buffs")
local el, eb = T.expectedRect("buffs", e.point, e.x, e.y)
check(near(l, el) and near(b, eb), "buffs stay where they were moved after Blizzard updates")
local b1l = BuffButton1:GetLeft()
local cbl = ConsolidatedBuffs:GetLeft()
check(b1l < cbl, "buff icons follow the moved root")
A:SetSetting("buffs", "alpha", 60)
check(near(BuffFrame:GetAlpha(), .6) and near(ConsolidatedBuffs:GetAlpha(), .6), "buff opacity")
-- bar 5 needs bar 4 on 3.3.5
A:ToggleElement("action4", false); A:ToggleElement("action5", false)
A:ToggleElement("action5", true)
check(MultiBarLeft:IsShown() and MultiBarRight:IsShown(), "enabling bar 5 also enables bar 4 so bar 5 actually shows")
check(A.editor.checks.action4:GetChecked() and A.editor.checks.action5:GetChecked(), "both boxes checked")
A:ToggleElement("action4", false)
check(not MultiBarLeft:IsShown() and not A.editor.checks.action5:GetChecked(), "turning bar 4 off turns bar 5 off")
-- Always Show Buttons: slot art, no attribute writes
local before = ActionButton5:GetAttribute("showgrid")
A:SetSetting("action2", "always", true)
check(MultiBarBottomLeftButton5:GetAttribute("showgrid") == 0 and ActionButton5:GetAttribute("showgrid") == before, "no showgrid attribute written (taint-free)")
local slots = A.elements.action2.slots
check(slots and slots[1] and slots[1]:IsShown() and slots[12]:IsShown(), "empty-slot art shown for every slot")
local sx, sy = slots[3]:GetCenter()
local bx, by = MultiBarBottomLeftButton3:GetCenter()
check(near(sx * slots[3]:GetEffectiveScale(), bx * MultiBarBottomLeftButton3:GetEffectiveScale(), 1), "slot art sits under its button")
A:SetSetting("action2", "icons", 8)
check(not slots[9]:IsShown() and slots[8]:IsShown(), "slot art follows # of icons")
A:SetSetting("action2", "always", false)
check(not slots[1]:IsShown(), "slot art hidden when off")
-- Bar Visible
A:SetSetting("action2", "visibility", "combat")
check(MultiBarBottomLeftButton1:GetAlpha() == 0 and not MultiBarBottomLeftButton1:IsMouseEnabled(), "In Combat bar hidden out of combat")
H.enterCombat()
check(MultiBarBottomLeftButton1:GetAlpha() == 1 and MultiBarBottomLeftButton1:IsMouseEnabled(), "In Combat bar shown when combat starts")
H.leaveCombat()
check(MultiBarBottomLeftButton1:GetAlpha() == 0, "hidden again after combat")
T.open()
A:SetSetting("action2", "visibility", "hidden")
check(MultiBarBottomLeftButton3:GetAlpha() == 0, "Hidden")
A:SetSetting("action2", "visibility", "always")
check(MultiBarBottomLeftButton3:GetAlpha() == 1, "Always")
check(#MOCK.blocked == 0, "no blocked actions from visibility changes")
-- micro menu order
A:SetSetting("micro", "order", "reverse")
check(HelpMicroButton:GetLeft() < CharacterMicroButton:GetLeft(), "micro menu Reverse order")
A:SetSetting("bags", "order", "reverse")
check(MainMenuBarBackpackButton:GetLeft() < CharacterBag3Slot:GetLeft(), "bags direction")
-- new elements
for _, id in ipairs({ "durability", "vehicleseat", "timers", "raidwarning", "tooltip" }) do
    check(T.overlay(id) and T.overlay(id):IsShown(), id .. " is editable")
    local l0, b0 = T.rect(id)
    T.dragElement(id, -30, -20)
    local l1, b1 = T.rect(id)
    check(near(l1 - l0, -30, 1) and near(b1 - b0, -20, 1), id .. " moves")
end
UIParent_ManageFramePositions(); H.tick(0.1, 2)
local de = A.draft.frames.durability
local dl, db = T.rect("durability")
local del, deb = T.expectedRect("durability", de.point, de.x, de.y)
check(near(dl, del) and near(db, deb) and DurabilityFrame:GetNumPoints() == 1, "durability stays put when the frame manager re-anchors it")
MultiActionBar_Update(); H.tick(0.1, 2)
check(VehicleSeatIndicator:GetNumPoints() == 1, "vehicle seat indicator keeps a single anchor")
GameTooltip_SetDefaultAnchor(GameTooltip, UIParent)
local tp, trel = GameTooltip:GetPoint(1)
check(trel == A.elements.tooltip.frame, "default tooltip anchors to the HUD Tooltip position")
-- chat is taken out of the frame manager (3.3.5 manages ChatFrame1)
check(UIPARENT_MANAGED_FRAME_POSITIONS.ChatFrame1 == nil, "chat unmanaged while in the layout")
check(A.elements.boss == nil, "boss frames not offered (3.3.5 re-anchors them in combat)")
-- nothing writes fields on Blizzard frames any more
check(CastingBarFrame.ignoreFramePositionManager == nil and ChatFrame1.ignoreFramePositionManager == nil, "no ignoreFramePositionManager written")
check(not PlayerFrame:IsUserPlaced() and not TargetFrame:IsUserPlaced(), "player/target not user-placed")
-- Classic restores everything new
A:RequestExit(); if T.confirmButton("Exit") then H.click(T.confirmButton("Exit")) end
A:LoadPreset("Classic")
check(UIPARENT_MANAGED_FRAME_POSITIONS.ChatFrame1 ~= nil, "chat managed again on Classic")
GameTooltip_SetDefaultAnchor(GameTooltip, UIParent)
tp, trel = GameTooltip:GetPoint(1)
check(trel == UIParent or trel == "UIParent", "tooltip default anchor back to Blizzard's")
check(near(BuffFrame:GetAlpha(), 1), "buff opacity restored")
